const dicts = { ru, en, uk }

export const languages = [
  { code: 'ru', name: 'Русский' },
  { code: 'en', name: 'English' },
  { code: 'uk', name: 'Українська' },
]

function systemLanguage() {
  for (const l of navigator.languages ?? [navigator.language]) {
    const code = l.slice(0, 2).toLowerCase()
    if (dicts[code]) return code
    if (code === 'be' || code === 'kk') return 'ru'
  }
  return 'en'
}

export const i18n = $state({ lang: systemLanguage() })

/** setLanguage('') follows the system language. */
export function setLanguage(code) {
  i18n.lang = dicts[code] ? code : systemLanguage()
  document.documentElement.lang = i18n.lang
}

export function t(key, params) {
  let s = dicts[i18n.lang][key] ?? en[key] ?? key
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, v)
  return s
}

/** Translates a backend error: "@key|detail" or plain text. */
export function tErr(e) {
  let s = String(e?.message ?? e)
  if (!s.startsWith('@')) return s
  const i = s.indexOf('|')
  const key = i < 0 ? s.slice(1) : s.slice(1, i)
  const detail = i < 0 ? '' : s.slice(i + 1)
  return t('err.' + key) + (detail ? (key === 'crashed' ? ' ' : ': ') + detail : '')
}

/** Short description of an account: service or offline. */
export function accountKind(a) {
  if (a.kind === 'microsoft') return 'Microsoft'
  if (a.kind === 'elyby') return 'Ely.by'
  return a.elySkin ? t('offlineSkin') : t('offline')
}

export function formatCount(n) {
  return new Intl.NumberFormat(i18n.lang, { notation: 'compact', maximumFractionDigits: 1 }).format(n)
}

export function formatDate(iso) {
  const d = new Date(iso)
  if (!iso || isNaN(d) || d.getFullYear() < 2000) return ''
  return d.toLocaleString(i18n.lang, { day: 'numeric', month: 'long', hour: '2-digit', minute: '2-digit' })
}
